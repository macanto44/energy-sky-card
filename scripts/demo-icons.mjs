// Writes demo/icons.js: the few MDI paths the card names, for the local demo
// and the README screenshots only (the card itself uses Home Assistant's <ha-icon>).
// @mdi/js is Apache 2.0 — see NOTICE.md.
import { writeFileSync } from 'node:fs';
import * as mdi from '@mdi/js';

const names = ['mdi:home-battery-outline', 'mdi:transmission-tower', 'mdi:sine-wave', 'mdi:solar-power-variant-outline'];
const camel = n => 'mdi' + n.slice(4).split('-').map(w => w[0].toUpperCase() + w.slice(1)).join('');
const paths = Object.fromEntries(names.map(n => {
    const path = mdi[camel(n)];
    if (!path) throw new Error(`Unknown icon ${n}`);
    return [n, path];
}));
writeFileSync('demo/icons.js', `// Generated by scripts/demo-icons.mjs from @mdi/js (Apache 2.0, Pictogrammers)\nexport const ICONS = ${JSON.stringify(paths, null, 2)};\n`);
console.log(`demo/icons.js: ${names.length} icons`);
